CREATE INDEX idx_day_offs_date ON amc.technician_day_offs (date);
CREATE INDEX idx_day_offs_mechanic ON amc.technician_day_offs (mechanic_uid);

CREATE TABLE amc.excluded_customers (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_uid text NOT NULL UNIQUE,
    jms_customer_id uuid,
    customer_name text,
    reason text,
    excluded_by text,
    created_at timestamptz DEFAULT now(),
    location_id bigint
);

CREATE TABLE amc.booking_activity (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_uid text NOT NULL,
    jms_job_id uuid,
    work_order_number text,
    customer_uid text,
    customer_name text,
    customer_phone text,
    asset_name text,
    action text NOT NULL CHECK (action IN ('confirmed', 'rescheduled', 'cancelled')),
    booked_by text,
    scheduled_date date,
    scheduled_time text,
    slot_label text,
    mechanic_name text,
    location_id bigint,
    details text,           -- mostly JSON, but not always
    created_at timestamptz DEFAULT now()
);
CREATE INDEX idx_booking_activity_job ON amc.booking_activity (job_uid);
CREATE INDEX idx_booking_activity_date ON amc.booking_activity (created_at);

CREATE TABLE amc.slot_reservations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date date NOT NULL,
    slot_label text NOT NULL,
    position_number integer NOT NULL,
    location_id bigint REFERENCES amc.locations(id),
    job_uid text,
    reserved_at timestamptz DEFAULT now(),
    expires_at timestamptz NOT NULL,
    UNIQUE (date, slot_label, position_number, location_id)
);

CREATE TABLE amc.booking_holds (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date date NOT NULL,
    slot_label text,
    position_number integer,
    location_id bigint,
    tech_uid text NOT NULL,
    jms_user_id uuid,
    start_ts bigint NOT NULL,   -- epoch milliseconds
    end_ts bigint NOT NULL,
    created_at timestamptz DEFAULT now(),
    expires_at timestamptz NOT NULL
);
CREATE INDEX idx_booking_holds_date ON amc.booking_holds (date, expires_at);

-- ── audit: one table per area, as the engine writes them ─────────────────────

DO $$
DECLARE area text;
BEGIN
  FOREACH area IN ARRAY ARRAY['auth', 'settings', 'users', 'locations', 'bookings', 'reminders', 'dayoffs'] LOOP
    EXECUTE format($f$
      CREATE TABLE amc.%1$I (
          id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          created_at timestamptz NOT NULL DEFAULT now(),
          actor_type text NOT NULL DEFAULT 'user',
          user_id bigint,
          user_email text,
          user_role text,
          location_id bigint,
          action text NOT NULL,
          entity_type text,
          entity_id text,
          summary text,
          metadata jsonb,
          method text,
          path text,
          status_code integer,
          ip text,
          request_id text
      );
      CREATE INDEX %2$I ON amc.%1$I (created_at);
      CREATE INDEX %3$I ON amc.%1$I (user_id);
      CREATE INDEX %4$I ON amc.%1$I (action);
      CREATE INDEX %5$I ON amc.%1$I (entity_type, entity_id);
    $f$, 'audit_' || area, 'idx_audit_' || area || '_created', 'idx_audit_' || area || '_user',
         'idx_audit_' || area || '_action', 'idx_audit_' || area || '_entity');
  END LOOP;
END $$;

CREATE VIEW amc.audit_all AS
  SELECT 'auth' AS domain, * FROM amc.audit_auth
  UNION ALL SELECT 'settings', * FROM amc.audit_settings
  UNION ALL SELECT 'users', * FROM amc.audit_users
  UNION ALL SELECT 'locations', * FROM amc.audit_locations
  UNION ALL SELECT 'bookings', * FROM amc.audit_bookings
  UNION ALL SELECT 'reminders', * FROM amc.audit_reminders
  UNION ALL SELECT 'dayoffs', * FROM amc.audit_dayoffs;

-- ── Business OS pattern: tenant and row-level security on every table ────────

DO $$
DECLARE t text;
BEGIN
  FOR t IN SELECT tablename FROM pg_tables WHERE schemaname = 'amc' LOOP
    EXECUTE format('ALTER TABLE amc.%I ADD COLUMN tenant_id uuid NOT NULL DEFAULT %L REFERENCES core.tenants(id)', t, '00000000-0000-0000-0000-000000000001');
    EXECUTE format('CREATE INDEX %I ON amc.%I (tenant_id)', t || '_tenant_idx', t);
    EXECUTE format('ALTER TABLE amc.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('CREATE POLICY service_role_all ON amc.%I FOR ALL TO service_role USING (true) WITH CHECK (true)', t);
  END LOOP;
END $$;

-- ── secrets ──────────────────────────────────────────────────────────────────

-- The engine's API keys live in Supabase Vault as 'amc/<key>' (global) and
-- 'amc/location/<location id>/<key>'. This is the only way to read them.
CREATE OR REPLACE FUNCTION amc.secret(p_name text) RETURNS text
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = vault, pg_temp AS $$
    SELECT decrypted_secret FROM vault.decrypted_secrets
     WHERE name = 'amc/' || p_name
     ORDER BY created_at DESC LIMIT 1
$$;
REVOKE ALL ON FUNCTION amc.secret(text) FROM PUBLIC;
COMMENT ON FUNCTION amc.secret(text) IS
  'AMC engine secrets from Vault: amc.secret(''zuper_api_token''), amc.secret(''location/3/whatsapp_api_key'').';

COMMIT;
